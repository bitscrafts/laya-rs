#!/usr/bin/env python3
"""Generate the differential fixture for the POST-PROCESSING step (logits -> Answer).

## Why this fixture exists

`make-head-fixture.py` pins the forward pass against PyTorch. That leaves the step *after* it
unpinned: temperature selection, the softmax, the confidence formula, the score expectation and the
`noul` override. Those are where a port diverges silently, because a wrong temperature still yields
a plausible distribution and a wrong confidence still yields a number in `[0, 1]`.

So this fixture is generated by calling the **reference's own functions** — `clamp_temperature`,
`temp_bucket`, `confidence_from_probs`, and the post-processing in `system_one` reproduced from its
source — over a table of logit vectors. The Rust `decide` module must reproduce every field.

## The cases, and why each one is here

* **A large raw logit** (~3000): the act logits in the real checkpoint are that size, so a softmax
  that forgot to subtract the max overflows to inf/nan here and nowhere else.
* **All-equal logits**: the maximum-entropy case. Confidence must be 0, and it is the case where a
  `log(k)` that used the wrong `k` is still wrong but *looks* fine.
* **k = 1**: the reference returns confidence 1.0 without touching the entropy at all.
* **A vector with a zero probability after softmax**: exercises the `1e-12` clip inside the log —
  without it this is `0 * log(0) == nan`, and the whole confidence becomes nan.
* **Each question type** (`choice`, `score`, `noul`) because they have different value rules and
  `noul` has its own confidence OVERRIDE (`max(p[1], 1-p[1])`, not the entropy).
* **Each bucket boundary** (k = 2, 3, 5, 6, 10, 11) because `temp_bucket` switches at those sizes,
  and k = 11 is the only bucket whose stored temperature is out of range.
* **A temperature that must be clamped** (the real `choice:11+ = 0.10058`), so the `bucket_clamped`
  flag has a true case.
* **Several temperatures that are NOT clamped** for the same logits, which is what proves F10: the
  label must be identical across all of them while the probabilities differ.
"""

from __future__ import annotations

import json
import math
import pathlib
import sys

import numpy as np

# The reference's own functions. Importing them rather than restating the formulas is the whole
# point: if the reference changes, this fixture changes with it.
from laya.common import (  # noqa: E402
    QTYPE_NAMES,
    QTYPES,
    clamp_temperature,
    confidence_from_probs,
    temp_bucket,
)

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/laya-head/tests/fixtures/decide.json"


def post_process(logits: list[float], qtype: int, k: int, t_scale: float, temperature_by_options: dict) -> dict:
    """The reference's post-processing, transcribed from `agent.py::system_one` lines 325-362.

    Transcribed rather than imported because the surrounding method needs a loaded model; the
    arithmetic is copied statement for statement, and the constants (`1e-12`, the clip) come from
    `confidence_from_probs`, which IS imported.
    """
    z = np.array(logits[:k], dtype=np.float64) / t_scale
    p = np.exp(z - z.max())
    p = p / p.sum()
    entropy_conf = confidence_from_probs(p, k)
    kind = QTYPE_NAMES[int(qtype)]
    if kind == "choice":
        value = int(p.argmax())
        conf = entropy_conf
    elif kind == "score":
        value = float((np.arange(k) * p).sum())
        conf = entropy_conf
    else:
        value = float(p[1])
        # agent.py line 360 OVERRIDES the entropy confidence for a noul with max(p[1], 1 - p[1]).
        # The first version of this fixture used the entropy form for every type, and the Rust test
        # failed — correctly, because the Rust matched the reference and the fixture did not.
        conf = max(float(p[1]), 1.0 - float(p[1]))
    return {
        "probabilities": [float(v) for v in p],
        "confidence": float(conf),
        "value": value,
        # The entropy form of the confidence, kept beside the reported one so a test can show that
        # `noul` OVERRIDES it rather than coincidentally agreeing.
        "entropy_confidence": float(entropy_conf),
        "raw_logit_gap": float(np.sort(np.array(logits[:k]))[-1] - np.sort(np.array(logits[:k]))[-2])
        if k >= 2
        else float(logits[0]),
    }


# (label, logits, qtype_index, k, configured temperature for the bucket, is the bucket a by_options one)
CASES = [
    ("choice_k2_clear", [3.5, -1.25], 0, 2, 1.0, False),
    ("choice_k2_near_tie", [0.9001, 0.9000], 0, 2, 1.0, False),
    ("choice_k3_even", [0.5, 0.5, 0.5], 0, 3, 1.0, False),
    ("choice_k5_one_zero_prob", [12.0, -12.0, -12.0, -12.0, -12.0], 0, 5, 1.0, False),
    ("choice_k11_clamped_bucket", [1.0] * 10 + [0.4], 0, 11, 0.10058, True),
    ("choice_k11_unclamped_same_logits", [1.0] * 10 + [0.4], 0, 11, 1.0, False),
    ("choice_k6_real_type_temp", [2.0, 1.0, 0.5, -0.5, -1.0, -2.0], 0, 6, 1.6369030475616455, True),
    ("choice_k10_by_options", [0.3, -0.2, 1.4, 0.0, 0.0, 2.2, -1.1, 0.7, 0.1, -0.9], 0, 10, 1.6369030475616455, False),
    ("score_k3", [1.1, 0.4, -0.7], 1, 3, 1.2514300346374512, True),
    ("score_k5", [-0.3, 0.2, 0.9, 1.7, -1.2], 1, 5, 1.2514300346374512, True),
    ("score_k2", [0.0, 0.0], 1, 2, 1.2514300346374512, True),
    ("noul_k2_yes_leaning", [0.25, 1.75], 2, 2, 1.983399510383606, True),
    ("noul_k2_no_leaning", [1.75, 0.25], 2, 2, 1.983399510383606, True),
    ("noul_k2_dead_even", [0.0, 0.0], 2, 2, 1.983399510383606, True),
    # NOTE: a k=1 `noul` is deliberately absent. The reference indexes `p[1]` unconditionally and
    # raises IndexError, so there is no reference behaviour to match — and a `noul` always has two
    # options by construction (`render_options` returns `[false, true]`). The Rust port handles the
    # degenerate case with a documented fallback and a Rust-side test, rather than inventing a
    # fixture value the reference never produced.
    # The act-head magnitude: a softmax that forgets to subtract the max overflows here.
    ("choice_k4_huge_logits", [3000.0, 2999.5, 1500.0, 0.0], 0, 4, 1.0, False),
]

# F10: the same logits under several IN-RANGE temperatures. The value must be identical across all
# of them while the probabilities differ.
F10_LOGITS = [0.30, 0.10, -0.20, 0.05]
F10_TEMPERATURES = [0.5, 0.75, 1.0, 1.6369030475616455, 2.5, 5.0]


def main() -> int:
    by_options = {"choice:2": 1.0, "choice:6-10": 1.6369030475616455, "score:3-5": 1.2514300346374512, "noul:2": 1.983399510383606}

    cases = []
    for label, logits, qtype, k, configured, from_bucket in CASES:
        t_scale = clamp_temperature(configured)
        entry = {
            "label": label,
            "logits": [float(v) for v in logits],
            "qtype": int(qtype),
            "k": int(k),
            "configured_temperature": float(configured),
            "temperature_used": float(t_scale),
            "temperature_was_clamped": bool(clamp_temperature(configured) != float(configured)),
            "temperature_from_bucket": bool(from_bucket),
            "bucket": temp_bucket(int(qtype), int(k)),
        }
        entry.update(post_process(logits, qtype, k, t_scale, by_options))
        cases.append(entry)

    f10 = []
    for t in F10_TEMPERATURES:
        out = post_process(F10_LOGITS, 0, len(F10_LOGITS), clamp_temperature(t), by_options)
        f10.append(
            {
                "temperature_configured": float(t),
                "temperature_used": float(clamp_temperature(t)),
                "probabilities": out["probabilities"],
                "value": out["value"],
            }
        )

    # A sanity check on the fixture itself, in the same spirit as the head fixture's: if the
    # reference disagrees with itself here, the fixture is broken and no Rust result can be trusted.
    values = {c["value"] for c in f10}
    if len(values) != 1:
        print(f"FIXTURE IS BROKEN: F10 cases disagree on the value: {values}", file=sys.stderr)
        return 1
    for c in cases:
        probs = c["probabilities"]
        if abs(sum(probs) - 1.0) > 1e-9:
            print(f"FIXTURE IS BROKEN: {c['label']} probabilities sum to {sum(probs)}", file=sys.stderr)
            return 1
        if not (0.0 <= c["confidence"] <= 1.0):
            print(f"FIXTURE IS BROKEN: {c['label']} confidence {c['confidence']} out of range", file=sys.stderr)
            return 1
        if not math.isfinite(c["confidence"]):
            print(f"FIXTURE IS BROKEN: {c['label']} confidence is not finite", file=sys.stderr)
            return 1

    doc = {
        "meta": {
            "generator": "scripts/make-decide-fixture.py",
            "source": "the reference's own clamp_temperature / temp_bucket / confidence_from_probs",
            "qtypes": {k: int(v) for k, v in QTYPES.items()},
            "temp_bucket_of_choice_11": temp_bucket(0, 11),
            "temp_bucket_of_choice_2": temp_bucket(0, 2),
            # The ONE deliberate divergence, stated so it is a decision rather than an oversight:
            # the reference `round(..., 4)`s every reported number (probabilities, confidence,
            # score, noul p) at the point it builds the response dict. This port keeps full f64
            # precision and rounds at the boundary that displays or publishes it. The values here
            # are therefore UNROUNDED and a parity check over a live corpus must compare with a
            # tolerance of at least 5e-5 rather than for equality.
            #
            # Rounding early is not harmless in this system: `Policy::band` compares a confidence
            # against thresholds, so a confidence rounded from 0.69996 to 0.7 can move a band and
            # change a route. Full precision in, rounding out.
            "deliberate_divergence": "reported numbers are NOT rounded to 4 dp, unlike the reference",
        },
        "cases": cases,
        "f10": f10,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, indent=2) + "\n")

    print(f"  wrote {OUT} ({OUT.stat().st_size} bytes)")
    print(f"  {len(cases)} post-processing cases, {len(f10)} F10 temperatures")
    print(f"  F10: the value is {values.pop()} at every temperature in {F10_TEMPERATURES}")
    clamped = [c["label"] for c in cases if c["temperature_was_clamped"]]
    print(f"  clamped cases: {clamped}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
